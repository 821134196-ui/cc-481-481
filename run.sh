#!/usr/bin/env bash
# 一条本地启动命令：重建虚构数据（自动准备拒领、缺页、止付样例）并启动系统。
set -euo pipefail
cd "$(dirname "$0")"

PORT="${1:-8000}"

echo "============================================================"
echo " 中国建设银行 · 支票簿领用与作废核验系统（虚构演示）"
echo " 启动后访问： http://127.0.0.1:${PORT}/"
echo " 已准备样例： 客户拒领 / 号码缺页 / 挂失止付 / 签收失败"
echo " 全部数据均为虚构，仅用于流程演示"
echo "============================================================"

exec python3 -m app.main --port "${PORT}"
